def recognize_patterns(major_stars):
    """识别命宫主星组合对应的格局。

    Args:
        major_stars: 命宫主星中文名列表，如 ['紫微','天府']。

    Returns:
        list of (格局名, 说明)。多星格局优先；单星坐命仅在该星未被
        多星格局覆盖时返回（避免"机巨同宫"同时报"天机坐命"等冗余）。
    """
    if not major_stars:
        return []
    stars = set(major_stars)
    multi = [p for p in PATTERNS if len(p[1]) >= 2 and p[1] <= stars]
    covered = set().union(*[p[1] for p in multi]) if multi else set()
    single = []
    for name, combo, desc in PATTERNS:
        if len(combo) == 1 and combo <= stars:
            s = next(iter(combo))
            if s not in covered:
                single.append((name, desc))
    return list(multi) + single


def recognize_patterns_from_chart(chart, ziwei_engine=None):
    """从ZiweiChart识别格局, 自动处理空宫借星(V2.6)。

    命宫空宫时, 借对宫(迁移宫)主星论格局(《紫微斗数全书》"空宫借对,虚实相生")。
    借星格局标注[借星], 与实星格局区分(借星力量打折)。

    Args:
        chart: ZiweiChart实例(需有palace_data含soul_borrowed/raw_soul_main_star)
        ziwei_engine: ZiweiEngine实例(用于full_chart获取迁移宫主星, 可选)

    Returns:
        list of (格局名, 说明)。空宫借星时格局名带[借星]前缀。
    """
    if not chart:
        return []
    pd = getattr(chart, 'palace_data', {}) or {}
    soul_borrowed = pd.get('soul_borrowed', False)
    raw_stars = pd.get('raw_soul_main_stars', []) or []
    # 优先用compute返回的全部主星(已含借星)
    all_stars = getattr(chart, 'soul_palace_main_stars', []) or []
    # 转为中文名(构建CHINESE_STAR_TO_KEY反向映射)
    from tongshu.engines.ziwei_engine import CHINESE_STAR_TO_KEY
    KEY_TO_CN = {v: k for k, v in CHINESE_STAR_TO_KEY.items()}
    cn_stars = [KEY_TO_CN.get(s, s) for s in all_stars if s]
    if not cn_stars and raw_stars:
        cn_stars = raw_stars
    patterns = recognize_patterns(cn_stars)
    if soul_borrowed and patterns:
        # 空宫借星, 格局标注[借星]
        return [(f"[借星]{name}", desc) for name, desc in patterns]
    return patterns
