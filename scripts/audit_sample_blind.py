# 分类定义
def classify_group(txt):
    """分组: 有描述组/无描述组/反证组/信息不足"""
    # 反证组: 原文明确写了破格字
    anti_patterns = [
        '失令', '失令', '失令', '失令',
        '天地交战', '交战',
        '坐下申金', '申金',
        '丁火独透', '独透',
    ]
    # 有描述组: 原文出现成格象描述
    desc_patterns = [
        '乘权', '全', '局全', '满局',
        '四柱皆', '皆水', '皆火', '皆木', '皆金', '皆土',
        '三透', '三逢', '三见',
        '仲春', '仲夏', '仲秋', '仲冬',
        '木局', '火局', '水局', '金局', '土局',
        '东方一气', '南方一气', '西方一气', '北方一气',
        '其势', '势泛溢', '势汪洋', '势旺盛',
    ]
    
    # 检查反证组
    for p in anti_patterns:
        if p in txt:
            return '反证组'
    
    # 检查有描述组
    for p in desc_patterns:
        if p in txt:
            return '有描述组'
    
    # 否则无描述组
    return '无描述组'

