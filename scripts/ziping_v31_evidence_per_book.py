def load(book):
    p = BASE / book / f"{book}_P0_passages.json"
    if not p.exists(): return []
    return json.loads(p.read_text(encoding="utf-8")).get("passages", [])


def is_real(text):
    if any(e in text[:300] for e in EXCLUDE): return False
    if text.count("* ") > 10: return False
    c = text.replace("\n","").replace(" ","").replace("*","").replace("#","")
    if len(c) < 60: return False
    return True


