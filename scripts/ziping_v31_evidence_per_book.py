def find_evidences(book, keywords, max_n=2):
    """对单典, 用关键词找到真原文证据."""
    out = []
    passages = load(book)
    for p in passages:
        text = p.get("original_text","")
        pid = p.get("passage_id","?")
        if not text or not is_real(text): continue
        # 必须有至少一个关键词
        kw_hit = next((k for k in keywords if k in text), None)
        if not kw_hit: continue
        out.append({"pid": pid, "kw": kw_hit, "snippet": text[:250].replace("\n"," ")})
        if len(out) >= max_n: break
    return out


