#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""边界用例扩充清单"""
import sys
sys.path.insert(0, '.')

from engines.special_pan import special_pan


def run(name, day_stem, branches, stems):
    result = special_pan(stems, branches, day_stem)
    print(f"{name}: {result}")
    return result


print("=== 边界用例扩充（第一批） ===")
print()

# 1. 杂气月——辰戌丑未月，藏干多且杂
print("--- 杂气月 ---")
run("辰月杂气(甲)", "甲", ["子", "辰", "子", "酉"], ["甲", "戊", "甲", "辛"])
run("戌月杂气(甲)", "甲", ["子", "戌", "子", "午"], ["甲", "戊", "甲", "丁"])
run("丑月杂气(甲)", "甲", ["子", "丑", "子", "午"], ["甲", "己", "甲", "丁"])
run("未月杂气(甲)", "甲", ["子", "未", "子", "午"], ["甲", "己", "甲", "丁"])

print()
# 2. 多冲——子午冲+卯酉冲
print("--- 多冲 ---")
run("子午冲(甲)", "甲", ["午", "子", "午", "子"], ["甲", "癸", "甲", "壬"])
run("卯酉冲(甲)", "甲", ["酉", "卯", "酉", "卯"], ["甲", "乙", "甲", "辛"])

print()
# 3. 多合——天干五合+地支六合
print("--- 多合 ---")
run("甲己合(甲)", "甲", ["子", "丑", "子", "亥"], ["甲", "己", "甲", "X"])
run("乙庚合(甲)", "甲", ["子", "酉", "子", "丑"], ["甲", "X", "甲", "乙"])

print()
# 4. 假从格——日主有微根但弱
print("--- 假从格 ---")
run("假从杀(甲)", "甲", ["申", "酉", "申", "酉"], ["甲", "辛", "甲", "癸"])
run("假从财(甲)", "甲", ["辰", "戌", "辰", "戌"], ["甲", "戊", "甲", "己"])
